#!/usr/bin/env python3
"""Build a standalone same-origin UI; no firmware writes or network access.

The deliberately small bundler accepts only this project's named local imports
and named const/function exports. It rejects unfamiliar syntax instead of
silently producing a partial module graph. No package downloads are required.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import quote

from live_backend import FEATURES, READS

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT/'designs/mxl-management'
OUTPUT = ROOT/'artifacts/native-ui'
IMPORT = re.compile(r"^import\s*\{([^}]+)\}\s*from\s*['\"]\./([\w-]+\.mjs)['\"];?\s*$", re.M)
EXPORT = re.compile(r'^export\s+(?:(?:async\s+)?function|const|let)\s+(\w+)', re.M)


def metadata(include_cli=True):
    inventory = json.loads((ROOT/'artifacts/candidates/xikestor-upload/shell-commands.json').read_text()) if include_cli else {'root_commands':[], 'commands':[]}
    data = {
        'READS': {k: {'path': v.path, 'method': v.method, 'stream': v.stream} for k,v in READS.items()},
        'FEATURES': [{'id': i, 'title': title, 'reads': reads} for i,title,reads in FEATURES],
        'CLI': {'root_commands': inventory['root_commands'], 'commands': [
            {k: c[k] for k in ['path','help','subcommands']} for c in inventory['commands']]},
    }
    return '// Generated by tools/build_native_ui.py from recovered V2 contracts.\n'+''.join(
        f'export const {key}='+json.dumps(value,ensure_ascii=False,separators=(',',':'))+';\n'
        for key,value in data.items())


def bundle(entry, overrides=None):
    modules = {}
    blocks = []
    visiting = set()

    def visit(name):
        if name in modules:
            return modules[name]
        if name in visiting:
            raise ValueError('Circular import: '+name)
        visiting.add(name)
        source = overrides[name] if overrides and name in overrides else (STATIC/name).read_text()
        exports = EXPORT.findall(source)
        def replace(match):
            names = match[1].strip()
            if not re.fullmatch(r'\w+(?:\s*,\s*\w+)*',names):
                raise ValueError('Unsupported named import: '+names)
            dep = visit(match[2])
            return f'const {{{names}}}={dep};'
        source = IMPORT.sub(replace, source)
        source = re.sub(r'^export\s+(?=(?:async\s+)?function|const|let)', '', source, flags=re.M)
        if re.search(r'^\s*(?:import|export)\b',source,re.M):
            raise ValueError('Unrecognized module syntax in '+name)
        ident = '__m'+str(len(modules))
        modules[name] = ident
        visiting.remove(name)
        if name == entry:
            blocks.append('(async()=>{\n'+source+'\n})();')
        else:
            blocks.append('const '+ident+'=(()=>{\n'+source+'\nreturn {'+','.join(exports)+'};\n})();')
        return ident
    visit(entry)
    return '\n'.join(blocks), list(modules)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--without-cli',action='store_true',help='Build without private extracted vendor CLI help')
    parser.add_argument('--output-dir',type=Path,default=OUTPUT)
    args=parser.parse_args()
    meta=metadata(not args.without_cli)
    if not args.without_cli:(STATIC/'native-metadata.mjs').write_text(meta)
    js, modules = bundle('live-app.mjs',{'native-metadata.mjs':meta})
    output=args.output_dir
    project_license=(ROOT/'LICENSE').read_text()
    if '*/' in project_license:raise ValueError('Unexpected licence comment terminator')
    js='/*\n'+project_license+'\n*/\n'+js
    css = '\n'.join((STATIC/name).read_text() for name in ['rtl-base.css','styles.css','live.css'])
    if '</style' in css.lower():
        raise ValueError('Unexpected style terminator')
    html = (STATIC/'live.html').read_text()
    favicon=(STATIC/'favicon.svg').read_text().strip()
    html=html.replace('href="favicon.svg"','href="data:image/svg+xml,'+quote(favicon,safe='')+'"')
    html = re.sub(r'<!--.*?-->\s*','',html,flags=re.S)
    html = html.replace('<meta charset="utf-8">','<meta charset="utf-8">\n  <meta name="mxl-transport" content="native">')
    html = re.sub(r'\s*<link rel="stylesheet" href="[^"]+">','',html)
    html = html.replace('</head>', '<style>\n'+css+'\n</style>\n</head>')
    license_text=(STATIC/'LICENSE-RTLPlayground').read_text()
    html=html.replace('href="LICENSE-RTLPlayground"','href="data:text/plain;charset=utf-8,'+quote(license_text,safe='')+'" download="LICENSE-RTLPlayground.txt"')
    html=html.replace('Connecting to the management service…','Connecting to the switch…')
    html=html.replace('<script type="module" src="live-app.mjs"></script>',
        '<script type="module">\n'+js.replace('</script','<\\/script')+'\n</script>')
    if re.search(r'<(?:script[^>]+src|link[^>]+rel="stylesheet")',html):
        raise ValueError('Standalone build retains external assets')
    raw=html.encode()
    output.mkdir(parents=True,exist_ok=True)
    (output/'switch-ui.html').write_bytes(raw)
    (output/'switch-ui.js').write_text(js)
    manifest={'cli_reference_included':not args.without_cli,'format':'mxl-native-ui/v1','target_firmware':'2.0.0.4','bytes':len(raw),
              'sha256':hashlib.sha256(raw).hexdigest(),'modules':modules,
              'same_origin_native_requests':True,'requires_python_on_switch':False,
              'flash_image':False,'inventory_persistence':'switch NVS when native endpoint is installed; explicit browser-local fallback on older builds'}
    (output/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest,indent=2))


if __name__=='__main__':
    main()
